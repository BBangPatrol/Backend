-- 가이드북을 옮겨 적는 과정에서 도로명이 잘못 들어갔다 (화↔회, 낭↔남, 복↔북 등).
-- 좌표는 카카오에서 받아 온 값이라 정확하다(현행 주소와 0m 차이). 주소 문자열만 틀렸다.
--
-- 그냥 두면 영수증 인증이 막힌다. 인증은 영수증의 주소와 가게 주소를 도로명으로 대조하는데,
-- 영수증에는 현행 주소가 찍히므로 이 다섯 곳은 정상 방문도 "다른 지점"으로 거절된다.
-- 사업자번호가 없는 굿베이글·시오네베이크샵은 주소가 유일한 확인 수단이라 아예 인증이 되지 않는다.
--
-- id 가 아니라 틀린 주소 값을 조건으로 쓴다. 다른 환경에서 이미 고쳐져 있으면 아무 것도 바꾸지 않는다.
-- 확인 근거: 카카오 로컬 API 의 현행 도로명 주소 (2026-09-19 조회)
