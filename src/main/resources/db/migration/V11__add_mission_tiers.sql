--
-- 목표치 상한 (V4 기준): 수집품 전체 92종 = 커먼 44 / 레어 28 / 에픽 14 / 레전더리 6.
-- 달성 불가능한 목표가 없도록 각 등급 상한 안에서만 단계를 만들었다.
-- DISTINCT_REGION 은 대전 5개 구가 전부라 이미 최대치(5)여서 추가할 단계가 없다.
